import assert from "node:assert/strict";
import { readFileSync,writeFileSync } from "node:fs";
import { dirname,join } from "node:path";
import { createClient } from "@supabase/supabase-js";
import { resolveEventSeason,getSeasonPlayers } from "../src/utils/seasons.js";
import { getTrainingAttendanceSummary,getPlayerMatchEntries } from "../src/utils/helpers.js";
const path=process.env.CALCIOLAB_LOCAL_PUBLIC_CONFIG;
const config=JSON.parse(readFileSync(path,"utf8").replace(/^\uFEFF/,""));
assert.match(config.url,/^http:\/\/(127\.0\.0\.1|localhost):54321\/?$/);
const fixture=JSON.parse(readFileSync(join(dirname(path),"calciolab-seasons-fixture.json"),"utf8"));
const ok=result=>{assert.ifError(result.error);return result.data;};
const login=async email=>{const client=createClient(config.url,config.publicKey,{auth:{persistSession:false,autoRefreshToken:false}});ok(await client.auth.signInWithPassword({email,password:"CalcioLab-QA!2026"}));return client;};
const owner=await login(fixture.ownerEmail);
const list=async(client,table)=>ok(await client.from(table).select("*").eq("team_id",fixture.teamId));
const catalog=await list(owner,"team_seasons");
assert.equal(catalog.length,2,"Create exactly the second season in the browser first.");
const first=catalog.find(row=>row.id===fixture.firstSeasonId),second=catalog.find(row=>row.name==="2026/27");
assert.ok(second);
const payload={p_team_id:fixture.teamId,p_request_id:second.request_id,p_name:second.name,p_start_date:second.start_date,p_end_date:second.end_date,p_source_season_id:first.id,p_player_ids:fixture.players.slice(0,2).map(player=>player.id)};
const replays=await Promise.all([owner.rpc("create_team_season",payload),owner.rpc("create_team_season",payload)]);
for(const result of replays) assert.equal(ok(result),second.id);
// Treat a committed response as lost, then retry with the persisted request identity.
await owner.rpc("create_team_season",payload);
assert.equal(ok(await owner.rpc("create_team_season",payload)),second.id);
assert.equal((await list(owner,"team_seasons")).length,2);
const conflict=await owner.rpc("create_team_season",{...payload,p_player_ids:[fixture.players[0].id]});
assert.match(conflict.error?.message||"",/SEASON_REQUEST_CONFLICT/);
const overlap=await owner.rpc("create_team_season",{...payload,p_request_id:crypto.randomUUID()});
assert.match(overlap.error?.message||"",/SEASON_OVERLAP/);
const invalidPlayer=await owner.rpc("create_team_season",{...payload,p_request_id:crypto.randomUUID(),p_name:"2027/28",p_start_date:"2027-07-01",p_end_date:"2028-06-30",p_source_season_id:second.id,p_player_ids:[fixture.players[2].id]});
assert.match(invalidPlayer.error?.message||"",/SEASON_PLAYER_INVALID/);
const rows=await list(owner,"team_season_players");
const decode=row=>({...row.data,id:row.id,_updatedAt:row.updated_at});
const members=rows.map(decode);
assert.equal(members.filter(row=>row.seasonId===first.id).length,3);
assert.equal(members.filter(row=>row.seasonId===second.id).length,3,"Add the new player in the browser first.");
const masters=(await list(owner,"players")).map(row=>({...row.data,id:row.id}));
assert.equal(masters.length,4,"The identity table contains three old players and one new identity, not copies.");
const oldSquad=getSeasonPlayers(masters,members,first.id),newSquad=getSeasonPlayers(masters,members,second.id);
const excluded=fixture.players[2].id;
assert.ok(oldSquad.some(player=>player.id===excluded));
assert.ok(!newSquad.some(player=>player.id===excluded));
const [a,b]=fixture.players;
const newPlayer=newSquad.find(player=>!fixture.players.some(old=>old.id===player.id));
assert.ok(newPlayer);
const sessions=(await list(owner,"sessions")).map(row=>({...row.data,id:row.id}));
const oldSessions=sessions.filter(event=>resolveEventSeason(event,catalog).season?.id===first.id);
const newSessions=sessions.filter(event=>resolveEventSeason(event,catalog).season?.id===second.id);
assert.equal(oldSessions.length,1);
assert.equal(newSessions.length,1);
assert.equal(newSessions[0].date,"2026-07-02");
assert.equal(newSessions[0].seasonId,second.id);
assert.equal(oldSessions[0].seasonId,undefined,"Legacy rows remain unchanged until explicitly edited.");
assert.equal(getTrainingAttendanceSummary(oldSquad.find(player=>player.id===a.id),oldSessions,{requireConfirmedPresence:true}).trainingPresences,1);
assert.equal(getTrainingAttendanceSummary(oldSquad.find(player=>player.id===excluded),oldSessions,{requireConfirmedPresence:true}).absences,1);
assert.equal(getTrainingAttendanceSummary(newSquad.find(player=>player.id===a.id),newSessions,{requireConfirmedPresence:true}).trainingPresences,1);
assert.equal(getTrainingAttendanceSummary(newSquad.find(player=>player.id===b.id),newSessions,{requireConfirmedPresence:true}).absences,1);
assert.equal(getTrainingAttendanceSummary(newPlayer,newSessions,{requireConfirmedPresence:true}).trainingPresences,1);
const match=(await list(owner,"matches")).map(row=>({...row.data,id:row.id})).find(row=>row.id===fixture.matchId);
assert.equal(getPlayerMatchEntries(oldSquad.find(player=>player.id===a.id),[match],[],false)[0].data.minutes,90);
assert.equal(getPlayerMatchEntries(oldSquad.find(player=>player.id===excluded),[match],[],false)[0].data.minutes,20);
const current=rows.find(row=>row.data.seasonId===second.id&&row.data.playerId===a.id);
ok(await owner.from("team_season_players").update({data:{...current.data,profile:{...current.data.profile,transferDate:"2026-11-12",notes:"Nota della seconda annata"}},updated_at:new Date().toISOString()}).eq("id",current.id).eq("updated_at",current.updated_at).select("id").single());
const fresh=await list(owner,"team_season_players");
assert.equal(fresh.find(row=>row.data.seasonId===first.id&&row.data.playerId===a.id).data.profile.transferDate,"");
assert.equal(fresh.find(row=>row.data.seasonId===first.id&&row.data.playerId===a.id).data.profile.notes,undefined);
const oldMembership=fresh.find(row=>row.data.seasonId===first.id&&row.data.playerId===a.id);
const denied=await owner.from("team_season_players").update({data:{...oldMembership.data,profile:{name:"Historical overwrite"}}}).eq("id",oldMembership.id).select("id");
assert.equal(ok(denied).length,0,"Historical membership is protected by RLS, including for an owner.");
const invalid=await owner.from("sessions").insert({id:"season-invalid-"+fixture.teamId,team_id:fixture.teamId,data:{title:"Invalid date",date:"2026-06-30",seasonId:second.id}});
assert.match(invalid.error?.message||"",/SEASON_EVENT_DATE/);
const missingId=await owner.from("sessions").insert({id:"season-missing-"+fixture.teamId,team_id:fixture.teamId,data:{title:"Missing season",date:"2026-07-03"}});
assert.match(missingId.error?.message||"",/SEASON_EVENT_REQUIRED/);
const temporaryMatch="season-match-"+fixture.teamId;
ok(await owner.from("matches").insert({id:temporaryMatch,team_id:fixture.teamId,data:{type:"Partita",opponent:"QA assegnazione gara",date:"2026-07-05",seasonId:second.id,season:second.name}}));
assert.equal(ok(await owner.from("matches").select("season_id").eq("id",temporaryMatch).eq("team_id",fixture.teamId).single()).season_id,second.id);
ok(await owner.from("matches").delete().eq("id",temporaryMatch).eq("team_id",fixture.teamId));
const assistant=await login(fixture.assistantEmail);
assert.equal((await list(assistant,"team_seasons")).length,2);
const forbiddenCreation=await assistant.rpc("create_team_season",{...payload,p_request_id:crypto.randomUUID()});
assert.match(forbiddenCreation.error?.message||"",/SEASON_FORBIDDEN/);
const noRosterEdit=await assistant.from("team_season_players").update({data:{...current.data,profile:{name:"Unauthorized"}}}).eq("id",current.id).select("id");
assert.equal(ok(noRosterEdit).length,0,"Existing roster-view permission remains view only.");
const collaboratorSession="season-staff-"+fixture.teamId;
ok(await assistant.from("sessions").insert({id:collaboratorSession,team_id:fixture.teamId,data:{type:"Allenamento",title:"QA collaboratore",date:"2026-07-03",seasonId:second.id,season:second.name,completed:true,attendance:{[b.id]:{status:"Presente"}}}}));
ok(await assistant.from("sessions").delete().eq("id",collaboratorSession).eq("team_id",fixture.teamId));
const outsider=await login(fixture.outsiderEmail);
assert.equal((await list(outsider,"team_seasons")).length,0);
assert.equal((await list(outsider,"team_season_players")).length,0);
assert.match((await outsider.rpc("create_team_season",{...payload,p_request_id:crypto.randomUUID()})).error?.message||"",/SEASON_FORBIDDEN/);
writeFileSync(join(dirname(path),"calciolab-seasons-verifica.json"),JSON.stringify({teamId:fixture.teamId,firstSeasonId:first.id,secondSeasonId:second.id,newPlayerId:newPlayer.id,newSessionId:newSessions[0].id,result:"PASS",checks:["concurrent replay","lost-response retry","request mismatch","stable player IDs","historical snapshot","legacy rows unchanged","crossing week","event date constraints","owner creation; assistant and outsider denied","collaborator view and attendance write","outsider denied"]},null,2));
console.log("PASS Supabase locale: due annate, replay concorrenti, storico e minuti conservati, settimana a cavallo, vincoli e permessi collaboratore/estraneo.");
