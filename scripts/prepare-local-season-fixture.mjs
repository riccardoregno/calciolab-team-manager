import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createClient } from "@supabase/supabase-js";
import { createServer } from "vite";
const configPath = process.env.CALCIOLAB_LOCAL_PUBLIC_CONFIG;
const config = JSON.parse(readFileSync(configPath,"utf8").replace(/^\uFEFF/,""));
assert.match(config.url,/^http:\/\/(127\.0\.0\.1|localhost):54321\/?$/);
assert.ok(process.env.CALCIOLAB_LOCAL_SERVICE_ROLE_KEY,"Local admin key required only to prepare Auth fixtures.");
const admin = createClient(config.url,process.env.CALCIOLAB_LOCAL_SERVICE_ROLE_KEY,{auth:{persistSession:false,autoRefreshToken:false}});
process.env.VITE_SUPABASE_URL=config.url;
process.env.VITE_SUPABASE_ANON_KEY=config.publicKey;
process.env.VITE_TEAM_BILLING_LOCAL_TEST="false";
const memory=new Map();
globalThis.localStorage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
const server=await createServer({server:{middlewareMode:true,hmr:false},appType:"custom"});
const ok = result => { assert.ifError(result.error); return result.data; };
try {
  const {supabase}=await server.ssrLoadModule("/src/lib/supabaseClient.js");
  const {ensureDefaultTeam}=await server.ssrLoadModule("/src/services/auth.js");
  const stamp=Date.now();
  const password="CalcioLab-QA!2026";
  const ownerEmail=`qa-seasons-owner-${stamp}@example.com`;
  const owner=ok(await supabase.auth.signUp({email:ownerEmail,password,options:{data:{first_name:"Mister",last_name:"Stagioni"}}}));
  assert.ok(owner.session);
  const {team,error}=await ensureDefaultTeam(owner.user);assert.ifError(error);
  ok(await admin.from("teams").update({name:"AS Due Annate · Collaudo",onboarding_completed:true}).eq("id",team.id));
  const players=["Alessandro De Santis Monteverde","Bruno Della Valle Castiglioni","Carlo Bianchi della Rovere"].map(name=>({id:crypto.randomUUID(),name,role:"Centrocampista",gruppo:"prima",status:"Disponibile",transferDate:"",injuries:[],absences:[]}));
  ok(await supabase.from("players").insert(players.map(({id,...data})=>({id,team_id:team.id,data}))));
  const sessionId=crypto.randomUUID(),matchId=crypto.randomUUID();
  ok(await supabase.from("sessions").insert({id:sessionId,team_id:team.id,data:{type:"Allenamento",title:"Ultima seduta prima annata",date:"2026-06-30",completed:true,duration:75,attendance:Object.fromEntries(players.map((p,i)=>[p.id,{status:i===2?"Assente":"Presente"}]))}}));
  ok(await supabase.from("matches").insert({id:matchId,team_id:team.id,data:{type:"Partita",title:"Ultima gara prima annata",opponent:"AS Esempio",matchKind:"Campionato",date:"2026-06-28",result:"1-0",completed:true,convocazione:{published:true,playerIds:players.map(p=>p.id)},attendance:Object.fromEntries(players.map((p,i)=>[p.id,{minutes:[90,0,20][i],goals:i===0?1:0}]))}}));
  const requestId=crypto.randomUUID();
  const payload={p_team_id:team.id,p_request_id:requestId,p_name:"2025/26",p_start_date:"2025-07-01",p_end_date:"2026-06-30",p_source_season_id:null,p_player_ids:players.map(p=>p.id)};
  const first=ok(await supabase.rpc("create_team_season",payload));
  assert.equal(ok(await supabase.rpc("create_team_season",payload)),first);
  const assistantEmail=`qa-seasons-staff-${stamp}@example.com`;
  const assistant=ok(await admin.auth.admin.createUser({email:assistantEmail,password,email_confirm:true,user_metadata:{first_name:"Assistente",last_name:"Stagioni"}})).user;
  ok(await admin.from("team_members").insert({team_id:team.id,user_id:assistant.id,role:"assistantCoach"}));
  ok(await admin.from("teams").update({settings:{members:[{id:"member-"+assistant.id,name:"Assistente Stagioni",email:assistantEmail,role:"assistantCoach",customAreas:{players:"view",trainings:"manage",matches:"manage",statistics:"view"}}]}}).eq("id",team.id));
  const outsiderEmail=`qa-seasons-outsider-${stamp}@example.com`;
  ok(await admin.auth.admin.createUser({email:outsiderEmail,password,email_confirm:true}));
  const fixture={teamId:team.id,ownerEmail,assistantEmail,outsiderEmail,firstSeasonId:first,sessionId,matchId,players,requestId};
  writeFileSync(join(dirname(configPath),"calciolab-seasons-fixture.json"),JSON.stringify(fixture,null,2));
  console.log("PASS fixture stagioni: prima annata con tre giocatori, gara e presenze; owner, collaboratore e account estraneo fittizi. Nessuna chiave salvata.");
} finally { await server.close(); }
